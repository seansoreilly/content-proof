import type { NextConfig } from "next";
import { execSync } from "child_process";

/**
 * Resolve the short commit hash for the build. Prefers the hash the hosting or
 * CI environment reports, falling back to the local git checkout.
 */
function getGitCommitHash(): string {
  const fromEnv =
    process.env.VERCEL_GIT_COMMIT_SHA ?? process.env.GITHUB_SHA ?? process.env.CI_COMMIT_SHA;
  if (fromEnv) return fromEnv.substring(0, 7);

  try {
    return execSync("git rev-parse --short HEAD", { encoding: "utf8" }).trim();
  } catch (error) {
    const errorMessage = error instanceof Error ? error.message : String(error);
    console.warn("Could not get git commit hash:", errorMessage);
    return "unknown";
  }
}

const commitHash = getGitCommitHash();

const isProduction = process.env.NODE_ENV === "production";

/**
 * Content-Security-Policy. Next's bootstrap scripts are inline, so script-src
 * needs 'unsafe-inline' (a nonce would force every page to render dynamically).
 * Development additionally needs 'unsafe-eval' and websockets for HMR.
 */
const contentSecurityPolicy = [
  "default-src 'self'",
  `script-src 'self' 'unsafe-inline'${isProduction ? "" : " 'unsafe-eval'"} https://www.googletagmanager.com`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob: https://www.google-analytics.com https://www.googletagmanager.com https://www.google.com",
  "font-src 'self' data:",
  [
    "connect-src 'self'",
    "https://www.google-analytics.com",
    "https://*.google-analytics.com",
    "https://*.analytics.google.com",
    "https://www.googletagmanager.com",
    "https://*.googletagmanager.com",
    // GA4 sends some beacons to www.google.com/g/collect
    "https://www.google.com",
    ...(isProduction ? [] : ["ws:", "wss:"]),
  ].join(" "),
  "worker-src 'self' blob:",
  "frame-ancestors 'none'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self' https://accounts.google.com",
  ...(isProduction ? ["upgrade-insecure-requests"] : []),
].join("; ");

const securityHeaders = [
  { key: "Content-Security-Policy", value: contentSecurityPolicy },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "DENY" },
  // Sign-in is a full-page redirect, never a popup, so isolating the window is free.
  { key: "Cross-Origin-Opener-Policy", value: "same-origin" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=(), payment=()" },
  { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains" },
];

/** Retired deployment hostnames that permanently forward to the canonical domain. */
const LEGACY_HOSTS = ["content-proof.vercel.app", "content-proof-melbourne-computing.vercel.app"];

const nextConfig: NextConfig = {
  // Build metadata inlined into every bundle. Using `env` rather than a webpack
  // DefinePlugin keeps this working under both webpack and Turbopack.
  env: {
    NEXT_PUBLIC_BUILD_COMMIT: commitHash,
    NEXT_PUBLIC_BUILD_TIME: new Date().toISOString(),
    NEXT_PUBLIC_BUILD_VERSION: `${commitHash}-${Date.now()}`,
  },
  async headers() {
    return [{ source: "/(.*)", headers: securityHeaders }];
  },
  // Exact hosts only (no wildcard) so preview deployments keep working.
  async redirects() {
    return [
      ...LEGACY_HOSTS.map((host) => ({
        source: "/:path*",
        has: [{ type: "host" as const, value: host }],
        destination: "https://www.contentproof.app/:path*",
        permanent: true,
      })),
      // The favicon is generated by src/app/icon.tsx; old bookmarks and
      // crawlers still ask for the conventional path.
      { source: "/favicon.ico", destination: "/icon", permanent: true },
    ];
  },
};

export default nextConfig;
